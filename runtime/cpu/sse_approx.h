inline uint32_t sse_rsqrt_bits(uint32_t u) {
    uint32_t ex = (u >> 23) & 0xFF, s = u & 0x80000000u;
    if (ex == 0) return s | 0x7F800000u;  // zero or denormal: infinity of its sign
    if (ex == 0xFF) {
        if (u & 0x7FFFFF) return u | 0x400000u;  // NaN, quieted
        return s ? 0xFFC00000u : 0;              // +inf 0, -inf the default NaN
    }
    if (s) return 0xFFC00000u;
    int e = int(ex) - 127, p = e & 1, k = (e - p) / 2;
    return uint32_t(126 - k) << 23 | uint32_t(kSseRsqrt[p * 1024 + ((u >> 13) & 1023)]) << 10;
}

inline uint32_t sse_rcp_bits(uint32_t u) {
    uint32_t ex = (u >> 23) & 0xFF, s = u & 0x80000000u;
    if (ex == 0) return s | 0x7F800000u;
    if (ex == 0xFF) return (u & 0x7FFFFF) ? (u | 0x400000u) : s;
    int re = 126 - (int(ex) - 127);
    if (re <= 0) return s;  // the answer would be denormal: zero
    return s | uint32_t(re) << 23 | uint32_t(kSseRcp[(u >> 12) & 2047]) << 10;
}

inline float sse_rsqrt(float v) {
    uint32_t u;
    std::memcpy(&u, &v, 4);
    u = sse_rsqrt_bits(u);
    std::memcpy(&v, &u, 4);
    return v;
}

inline float sse_rcp(float v) {
    uint32_t u;
    std::memcpy(&u, &v, 4);
    u = sse_rcp_bits(u);
    std::memcpy(&v, &u, 4);
    return v;
}
